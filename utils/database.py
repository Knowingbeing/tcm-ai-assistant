# Streamlit Cloud 使用 /tmp，本地使用项目目录
if os.path.exists("/tmp"):
    DATA_DIR = "/tmp"
else:
    DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "data")
    os.makedirs(DATA_DIR, exist_ok=True)

DB_PATH = os.path.join(DATA_DIR, "tcm_consultation.db")

# 全局数据库连接（缓存）
_connection = None

def get_connection():
    global _connection
    if _connection is None:
        _connection = sqlite3.connect(DB_PATH, check_same_thread=False)
        _connection.row_factory = sqlite3.Row
    return _connection

def init_database():
    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS patients (
        patient_id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL,
        gender TEXT CHECK(gender IN ('男', '女')),
        age INTEGER,
        constitution TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS syndromes (
        syndrome_id INTEGER PRIMARY KEY AUTOINCREMENT,
        syndrome_name TEXT NOT NULL UNIQUE,
        category TEXT,
        sub_category TEXT,
        description TEXT,
        common_symptoms TEXT,
        tongue_sign TEXT,
        pulse_sign TEXT,
        treatment_principle TEXT,
        source TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS formulas (
        formula_id INTEGER PRIMARY KEY AUTOINCREMENT,
        formula_name TEXT NOT NULL UNIQUE,
        composition TEXT,
        function TEXT,
        indication TEXT,
        source_book TEXT,
        category TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS symptoms (
        symptom_id INTEGER PRIMARY KEY AUTOINCREMENT,
        symptom_name TEXT NOT NULL UNIQUE,
        category TEXT,
        sub_category TEXT,
        description TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS herbs (
        herb_id INTEGER PRIMARY KEY AUTOINCREMENT,
        herb_name TEXT NOT NULL UNIQUE,
        nature TEXT,
        flavor TEXT,
        meridian_tropism TEXT,
        function TEXT,
        indication TEXT,
        dosage TEXT,
        contraindication TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS consultations (
        consultation_id INTEGER PRIMARY KEY AUTOINCREMENT,
        patient_id INTEGER NOT NULL,
        chief_complaint TEXT NOT NULL,
        symptom_description TEXT,
        tongue_sign TEXT,
        pulse_sign TEXT,
        ai_diagnosed_syndrome_id INTEGER,
        ai_confidence REAL,
        ai_recommended_formula_id INTEGER,
        doctor_confirmed INTEGER DEFAULT 0,
        doctor_notes TEXT,
        consultation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
        FOREIGN KEY (ai_diagnosed_syndrome_id) REFERENCES syndromes(syndrome_id),
        FOREIGN KEY (ai_recommended_formula_id) REFERENCES formulas(formula_id)
    )
    """)

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS consultation_symptoms (
        consultation_id INTEGER NOT NULL,
        symptom_id INTEGER NOT NULL,
        severity INTEGER DEFAULT 1,
        duration TEXT,
        PRIMARY KEY (consultation_id, symptom_id),
        FOREIGN KEY (consultation_id) REFERENCES consultations(consultation_id),
        FOREIGN KEY (symptom_id) REFERENCES symptoms(symptom_id)
    )
    """)

    conn.commit()

